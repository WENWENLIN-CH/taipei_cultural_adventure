// Read-only preflight: no cloud calls and no deployment.
import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
const read=p=>readFileSync(p,"utf8");
const deploy=JSON.parse(read("firebase.functions-pilot.json"));
const pkg=JSON.parse(read("functions/package.json"));
const fn=read("functions/index.js");
const handler=read("functions/submission-handler.js");
const rules=read("docs/firestore-group-draft.rules");
const preview=read("cloud-quest-bootstrap.js");
const build=read("scripts/build-cloud-quest-preview.mjs");
assert.equal(deploy.functions.source,"functions","Pilot must only deploy functions/");
assert.equal(deploy.functions.codebase,"pilot-submit","Pilot codebase must be isolated");
assert.ok(!("hosting" in deploy),"Pilot config must not deploy hosting");
assert.ok(!("firestore" in deploy),"Pilot config must not deploy rules");
assert.equal(pkg.engines.node,"22","Runtime changed; check deployment compatibility");
assert.match(fn,/region:"asia-east1"/);
assert.match(fn,/request\.data\?\.activityId!=="demo2026"/);
assert.match(fn,/request\.data\?\.groupId!=="group01"/);
assert.match(fn,/Number\(request\.data\?\.missionId\)!==3/);
assert.match(handler,/if\(!uid \|\| !anonymous\)/);
assert.match(handler,/if\(!member\.exists\)/);
assert.match(handler,/await file\.exists\(\)/);
assert.match(handler,/await db\.runTransaction/);
assert.match(handler,/tx\.create\(missionRef/);
assert.match(rules,/match \/missions\/\{missionId\}/);
assert.match(rules,/allow create, update, delete: if false;/);
assert.match(preview,/const SUBMISSIONS_ENABLED=false;/);
assert.match(build,/cloud-quest\.html/);
