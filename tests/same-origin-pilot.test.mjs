import {execFileSync} from "node:child_process";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import assert from "node:assert/strict";
const read=p=>readFileSync(p,"utf8");
const digest=p=>createHash("sha256").update(readFileSync(p)).digest("hex");
const original=[digest("index.html"),digest("script.js")];
execFileSync(process.execPath,["scripts/build-same-origin-pilot.mjs"],{stdio:"inherit"});
assert.deepEqual([digest("index.html"),digest("script.js")],original);
const home=read(".firebase-preview/cloud-quest.html");
const pilot=read(".firebase-preview/pilot-quest.html");
const safeBoot=read(".firebase-preview/cloud-quest-bootstrap.js");
const pilotBoot=read(".firebase-preview/cloud-quest-pilot-bootstrap.js");
assert.ok(home.includes('src="cloud-quest-bootstrap.js"'));
assert.ok(!home.includes('src="cloud-quest-pilot-bootstrap.js"'));
assert.ok(pilot.includes('src="cloud-quest-pilot-bootstrap.js"'));
assert.ok(!pilot.includes('src="cloud-quest-bootstrap.js"'));
assert.ok(safeBoot.includes("const SUBMISSIONS_ENABLED=false;"));
assert.ok(pilotBoot.includes("const SUBMISSIONS_ENABLED=true;"));
assert.ok(pilotBoot.includes('const PILOT_GROUP="group01";'));
assert.ok(pilotBoot.includes("const PILOT_MISSION=3;"));
assert.ok(pilotBoot.includes('group.activityId==="demo2026"'));
assert.ok(pilotBoot.includes('group.groupId!==PILOT_GROUP'));
assert.ok(pilotBoot.includes('Number(missionId)!==PILOT_MISSION'));
assert.ok(read(".firebase-preview/cloud-quest.js").includes('btn.disabled=true'));
assert.ok(read(".firebase-preview/cloud-quest.js").includes('window.cloudQuestCompleted?.(m.id)'));
assert.equal(digest(".firebase-preview/cloud-quest.js"),digest(".firebase-pilot-preview/cloud-quest.js"));
console.log("PASS: same Hosting origin contains read-only /cloud-quest.html and restricted /pilot-quest.html.");
console.log("PASS: original website unchanged; existing anonymous S02 credentials are NOT copied.");
console.log("Build only. No deployment performed.");
