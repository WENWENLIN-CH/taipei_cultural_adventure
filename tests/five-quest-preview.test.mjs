import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
const read=p=>readFileSync(p,"utf8");
const hash=p=>createHash("sha256").update(readFileSync(p)).digest("hex");
const originals={html:hash("index.html"),js:hash("script.js"),boot:hash("cloud-quest-bootstrap.js")};
execFileSync(process.execPath,["scripts/build-five-quest-preview.mjs"],{stdio:"inherit"});
assert.equal(hash("index.html"),originals.html,"Never modify GitHub Pages homepage");
assert.equal(hash("script.js"),originals.js,"Never modify GitHub Pages mission logic");
assert.equal(hash("cloud-quest-bootstrap.js"),originals.boot,"Never unlock existing pilot by editing source");
const html=read(".firebase-preview/five-quest.html");
const js=read(".firebase-preview/five-quest.js");
const bootstrap=read(".firebase-preview/cloud-quest-bootstrap.js");
const baseJS=read(".firebase-preview/cloud-quest.js");
const flow=read(".firebase-preview/mission-cloud-flow.js");
const recovery=read(".firebase-preview/mission-upload-recovery.js");
const pilotBuilder=read("scripts/build-same-origin-pilot.mjs");
assert.ok(html.includes("五關學生預覽（唯讀）"));
assert.ok(html.includes('id="fiveQuestReadOnlyNotice"'));
assert.ok(html.includes('src="five-quest.js"'));
assert.ok(!html.includes('src="cloud-quest.js"'));
assert.ok(html.includes('src="cloud-quest-bootstrap.js"'));
assert.ok(js.includes('const STORAGE_KEY = "taipeiCulturalQuestFiveReadOnlyV1";'));
assert.ok(!js.includes('const STORAGE_KEY = "taipeiCulturalQuestCloudPreviewV1";'));
assert.ok(baseJS.includes('const STORAGE_KEY = "taipeiCulturalQuestCloudPreviewV1";'),"Original preview key must be unchanged");
assert.ok(bootstrap.includes("const SUBMISSIONS_ENABLED=false;"));
assert.ok(bootstrap.includes("const PILOT_MISSION=3;"));
assert.ok(pilotBuilder.includes("const PILOT_MISSION=3;"),"Existing pilot must remain restricted");
assert.ok(js.includes("return doneCount()===5;"),"Final mission requires all 5 Firestore completions");
assert.ok(js.includes('window.cloudQuestCompleted?.(m.id)'),"Five-quest passport must be cloud driven");
assert.ok(js.includes('const done = Boolean(window.cloudQuestCompleted?.(id));'),"Island pins must use cloud");
assert.ok(!js.includes("    ms.completed = true;"),"Local drafts must not mark cloud completion");
assert.ok(js.includes('document.getElementById("completeMissionBtn").disabled = !window.cloudQuestMaySubmit?.(m.id);'),"No active submit buttons");
assert.ok(js.includes('const btn=document.getElementById("completeMissionBtn");'));
assert.ok(js.includes('if(!window.cloudQuestMaySubmit?.(m.id))'),"Always check gate again at click");
assert.ok(js.includes('state.teacherUnlocked = false;'),"No local teacher unlock");
assert.ok(recovery.includes("uploadMissionWithRecovery"),"Dependency must be copied for browser import");
assert.ok(flow.includes('from "./mission-upload-recovery.js"'),"Flow must resolve new recovery module");
assert.ok(html.includes("清除本機草稿"),"Reset must be clearly local-only");
for(const name of ["1","2","3","4","5"])assert.ok(html.includes('data-mission="'+name+'"'),"Mission "+name+" must be present");
console.log("Five-quest isolated read-only build checks passed. No deployments or live writes.");
