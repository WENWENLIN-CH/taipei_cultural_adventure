import {execFileSync} from "node:child_process";
import {readFileSync} from "node:fs";
import {createHash} from "node:crypto";
import assert from "node:assert/strict";
const text=p=>readFileSync(p,"utf8");
const hash=p=>createHash("sha256").update(readFileSync(p)).digest("hex");
const originalHTML=hash("index.html"),originalJS=hash("script.js");
execFileSync(process.execPath,["scripts/build-pilot-preview.mjs"],{stdio:"inherit"});
assert.equal(hash("index.html"),originalHTML,"Formal website must remain unchanged");
assert.equal(hash("script.js"),originalJS,"Formal quest script must remain unchanged");
const readonly=text(".firebase-preview/cloud-quest-bootstrap.js");
const pilot=text(".firebase-pilot-preview/cloud-quest-bootstrap.js");
const script=text(".firebase-pilot-preview/cloud-quest.js");
const config=JSON.parse(text("firebase.hosting-pilot.json"));
assert.ok(readonly.includes("const SUBMISSIONS_ENABLED=false;"),"Normal preview must stay read-only");
assert.ok(pilot.includes("const SUBMISSIONS_ENABLED=true;"),"Pilot output must opt-in");
assert.ok(pilot.includes('const PILOT_GROUP="group01";'),"Pilot group must be fixed");
assert.ok(pilot.includes("const PILOT_MISSION=3;"),"Pilot mission must be fixed");
assert.ok(pilot.includes('group.activityId==="demo2026"'),"Pilot activity must be fixed");
assert.ok(script.includes("confirm(\"確認代表第一組提交第三關共同成果"),"Pilot must ask for explicit confirmation");
assert.ok(script.includes('btn.textContent="照片上傳與成果驗證中…"'),"Must display progress");
assert.ok(script.includes("btn.disabled=true"),"Double-submit prevention required");
assert.ok(!script.includes("    ms.completed = true;"),"No local completed status allowed");
assert.equal(config.hosting.public,".firebase-pilot-preview","Pilot must deploy isolated directory");
assert.equal(hash(".firebase-preview/cloud-quest.js"),hash(".firebase-pilot-preview/cloud-quest.js"),"Same island logic in both previews");
console.log("Pilot build checks passed: normal preview remains read-only; isolated mission3 submission pilot generated. NOT deployed.");
